#!/usr/bin/env bash
set -Eeuo pipefail

# DevOS Forge V1 Stage C — read-only Git SSH preflight.
# This script does not change sshd, authorized_keys, Forgejo config, firewall,
# users, repositories, or runners.

FORGEJO_CONFIG="/etc/forgejo/app.ini"
FORGEJO_HOME="/var/lib/forgejo"
FORGEJO_USER="git"
DOMAIN="git.criandofacil.com.br"

say() { printf '\n===== %s =====\n' "$*"; }

if [[ $EUID -ne 0 ]]; then
  echo "Run with sudo: sudo bash $0" >&2
  exit 1
fi

say "STAGE C — GIT SSH PREFLIGHT"
echo "domain=${DOMAIN}"
echo "forgejo_user=${FORGEJO_USER}"

say "HTTPS HEALTH"
curl -fsS "https://${DOMAIN}/api/healthz" || {
  echo "HTTPS health failed" >&2
  exit 1
}
echo

say "FORGEJO SERVICE"
systemctl is-active forgejo
systemctl is-enabled forgejo

say "OPENSSH SERVICE / LISTENER"
systemctl is-active ssh || systemctl is-active sshd
ss -lntp | grep -E '(^|[[:space:]])[^[:space:]]*:22[[:space:]]' || true

say "EFFECTIVE SSHD SETTINGS"
sshd -T 2>/dev/null \
  | grep -E '^(port|pubkeyauthentication|passwordauthentication|authorizedkeysfile|strictmodes|permitrootlogin) ' \
  | sort

say "FORGEJO GIT OS ACCOUNT"
getent passwd "$FORGEJO_USER"
id "$FORGEJO_USER"

say "FORGEJO SSH PATHS"
for p in "$FORGEJO_HOME" "$FORGEJO_HOME/.ssh" "$FORGEJO_HOME/.ssh/authorized_keys"; do
  if [[ -e "$p" ]]; then
    stat -c '%A %a %U:%G %n' "$p"
  else
    echo "MISSING $p"
  fi
done

say "FORGEJO SSH CONFIG (NON-SECRET)"
awk '
  BEGIN { in_server=0 }
  /^[[:space:]]*\[server\][[:space:]]*$/ { in_server=1; next }
  /^[[:space:]]*\[/ { in_server=0 }
  in_server && /^[[:space:]]*(DOMAIN|ROOT_URL|START_SSH_SERVER|SSH_DOMAIN|SSH_PORT|SSH_CREATE_AUTHORIZED_KEYS_FILE)[[:space:]]*=/ { print }
' "$FORGEJO_CONFIG"

say "AUTHORIZED KEYS SUMMARY"
if [[ -f "$FORGEJO_HOME/.ssh/authorized_keys" ]]; then
  key_lines=$(grep -Ec '(^|[[:space:]])(ssh-(ed25519|rsa)|ecdsa-sha2-|sk-ssh-|sk-ecdsa-)' "$FORGEJO_HOME/.ssh/authorized_keys" || true)
  forgejo_commands=$(grep -Ec 'forgejo.*serv key-|gitea.*serv key-' "$FORGEJO_HOME/.ssh/authorized_keys" || true)
  echo "public_key_lines=${key_lines}"
  echo "forgejo_command_lines=${forgejo_commands}"
else
  echo "authorized_keys=absent"
fi

say "DNS / SSH HOST REACHABILITY"
getent ahostsv4 "$DOMAIN" | sed -n '1,6p'

say "PREFLIGHT RESULT"
echo "Read-only Stage C preflight complete."
echo "No SSH key was added or regenerated by this script."
echo "Next gate: add one intended client public key to the Forgejo user, regenerate/verify authorized_keys if needed, then test: ssh -T git@${DOMAIN}"
